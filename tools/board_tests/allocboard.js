const { chromium } = require('/tmp/pwtest/node_modules/playwright-core');
(async()=>{
  const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1194/chrome-linux/chrome',args:['--no-sandbox']});
  const p=await b.newPage({viewport:{width:1920,height:1080}}); const errs=[]; p.on('pageerror',e=>errs.push(e.message));
  const calls=[];
  await p.route('**/rest/v1/**',async route=>{
    const url=route.request().url(); const m=url.match(/rpc\/([a-z_]+)/); let body=null; const q=JSON.parse(route.request().postData()||'{}');
    if(m){ const fn=m[1]; if(/^admin_|^login$/.test(fn)) calls.push({fn,q});
      if(fn==='login') body=q.p_pass==='good'?{ok:true,admin:true,name:'طارق'}:{ok:false,msg:'خطأ'};
      else if(fn==='admin_load_tv_alloc') body={ok:true,count:q.p_rows.length,msg:'ok'};
      else if(fn==='admin_load_tv_banks') body={ok:true,count:q.p_rows.length};
      else if(fn==='admin_mark_synced') body={ok:true};
      else if(fn==='get_live_board') body={ok:true,empty:true};
      else body=fn==='get_dashboard_targets'?{ok:true,scopes:{}}:[];
    } else body=[];
    return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(body)});
  });
  await p.goto('file:///home/user/Tareq/NHC_Live_Board.html?page=1',{waitUntil:'load'}); await p.waitForTimeout(1200);
  await p.keyboard.press('u'); await p.waitForTimeout(200);
  await p.setInputFiles('#tvUpFile',process.argv[2]); await p.waitForFunction(()=>/ملف التخصيص|تعذّر|لم أ/.test(document.getElementById('tvUpMsg').innerText),null,{timeout:600000});
  console.log('summary:',await p.evaluate(()=>document.getElementById('tvUpMsg').innerText.replace(/\n/g,' | ')));
  console.log('go label:',await p.evaluate(()=>document.getElementById('tvUpGo').textContent),'| time row hidden:',await p.evaluate(()=>document.getElementById('tvUpAtRow').style.display));
  await p.fill('#tvUpUser','tareq'); await p.fill('#tvUpPass','good'); await p.click('#tvUpGo');
  await p.waitForFunction(()=>/✓|تعذّر|خطأ/.test(document.getElementById('tvUpMsg').innerText),null,{timeout:600000});
  console.log('result:',await p.evaluate(()=>document.getElementById('tvUpMsg').innerText));
  const sum=fn=>calls.filter(c=>c.fn===fn);
  console.log('alloc calls:',sum('admin_load_tv_alloc').map(c=>c.q.p_table+':'+c.q.p_rows.length+(c.q.p_reset?'R':'')).join(','),'| banks:',sum('admin_load_tv_banks').map(c=>c.q.p_rows.length).join(','),'| synced:',sum('admin_mark_synced').length,'| creds on all:',calls.filter(c=>c.fn!=='login').every(c=>c.q.p_admin==='tareq'&&c.q.p_pass==='good'));
  const con=sum('admin_load_tv_alloc').filter(c=>c.q.p_table==='contracts').flatMap(c=>c.q.p_rows);
  console.log('contracts total:',con.reduce((a,r)=>a+r.cnt,0),'priced:',con.reduce((a,r)=>a+r.price_n,0),'sample:',JSON.stringify(con[0]));
  console.log('PAGE ERRORS:',errs.length,errs.join(' | '));
  await b.close();
})();
